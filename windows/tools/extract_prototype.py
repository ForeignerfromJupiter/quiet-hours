#!/usr/bin/env python3
"""Copy the eight style renderers out of reference/prototype.html into windows/web/.

The prototype is the visual and motion source of truth, so the Windows saver runs its renderers
as they are instead of a hand port. This script copies, verbatim:

  * the JavaScript from the "Hinge" banner up to (not including) the "app" banner, i.e. every
    style object, palette and helper the styles use, but none of the page's own UI code;
  * the CSS from the "Hinge" banner to the end of the <style> block, plus the .fill and
    .corner-label rules the styles rely on.

The output files are committed. CI re-runs this script and fails if they changed, so the
Windows build can never drift from the prototype silently.

Usage: python3 -I windows/tools/extract_prototype.py   (from the repo root, or anywhere)
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "reference" / "prototype.html"
OUT = ROOT / "windows" / "web"

JS_START = "/* ================= Hinge ================= */"
JS_END = "/* ================= app ================= */"
CSS_START = "/* ---------- Hinge ---------- */"

HEADER = (
    "GENERATED by windows/tools/extract_prototype.py from reference/prototype.html.\n"
    "Do not edit: change the prototype and re-run the script."
)


def between(text: str, start: str, end: str) -> str:
    i = text.find(start)
    j = text.find(end, i + 1)
    if i < 0 or j < 0:
        sys.exit(f"extract_prototype: marker not found: {start!r} … {end!r}")
    return text[i:j]


def write(path: pathlib.Path, text: str) -> None:
    with open(path, "w", encoding="utf-8", newline="\n") as f:  # LF on every OS, so CI can diff
        f.write(text)


def main() -> None:
    html = SRC.read_text(encoding="utf-8")

    script = between(html, "<script>", "</script>")
    js = between(script, JS_START, JS_END).rstrip() + "\n"

    style = between(html, "<style>", "</style>")
    css = between(style + "\n</style>", CSS_START, "\n</style>").rstrip() + "\n"
    shared = [m.group(0) for m in re.finditer(r"^\.(?:fill|corner-label)\{.*\}$", style, re.M)]
    if len(shared) != 2:
        sys.exit("extract_prototype: .fill / .corner-label rules not found")

    OUT.mkdir(parents=True, exist_ok=True)
    write(OUT / "styles.gen.js", f"/* {HEADER} */\n{js}")
    write(OUT / "styles.gen.css", f"/* {HEADER} */\n" + "\n".join(shared) + "\n\n" + css)
    print(f"extract_prototype: wrote {len(js)} bytes of JS and {len(css)} bytes of CSS")


if __name__ == "__main__":
    main()
